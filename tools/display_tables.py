#!/usr/bin/env python
"""display_tables.py -- regenerate the printed decimal tables from the exact rationals stored in results/, with
outward (safe-direction) rounding: lower ends rounded DOWN, upper ends rounded UP. Writes results/DISPLAY-TABLES.md.

Why: the lab's engine log printed upper ends truncated (rounded down in the last digit), and some VERDICT tables copied
those prints (results/ERRATA.md item 1). The exact rationals were always right; this file is the corrected display.
Run from anywhere:  python tools/display_tables.py
"""
import json
import os
from fractions import Fraction

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, 'results')
DIG = 18


def F(s):
    return Fraction(str(s))


def down(x, k=DIG):
    n = x.numerator * 10 ** k // x.denominator
    return fmt(n, k)


def up(x, k=DIG):
    n = -((-x.numerator * 10 ** k) // x.denominator)
    return fmt(n, k)


def fmt(n, k):
    s = '-' if n < 0 else ''
    n = abs(n)
    return '%s%d.%0*d' % (s, n // 10 ** k, k, n % 10 ** k)


def load(p):
    return json.load(open(os.path.join(R, p), encoding='utf-8'))


def pick(nodes, wanted, jkey):
    out = []
    for w in wanted:
        hit = [n for n in nodes if F(n[jkey]) == w]
        out.append((w, hit[0] if hit else None))
    return out


def main():
    L = ['# Display tables (outward rounding from the stored exact rationals)', '',
         'Generated by `tools/display_tables.py`. Every lower end is the exact lower end rounded down and every upper end',
         'the exact upper end rounded up, to %d decimals unless stated. Source fields: `delta_lo` / `delta_hi` (P2a-P2c),' % DIG,
         '`point.delta_lo_exact` / `point.delta_hi_exact` (P2d, P2e), `c`, `X3`, `chi_lo` / `chi_hi` (exact "p/q" strings).',
         'delta = M_ADM - 1 at mu = 1; j = 4J; chi = J / M_ADM^2.', '']
    for tag, path, wanted in (('P2a', 'p2a/result_p2a.json', [1, 2, 4, 6, 8, 10]),
                              ('P2b', 'p2b/result_p2b.json', [10, 30, 100, 300, 1000]),
                              ('P2c', 'p2c/result_p2c.json', [3000, 10000])):
        d = load(path)
        nodes = d['nodes']
        rows = pick(nodes, [Fraction(w) for w in wanted], 'j') + [('last', nodes[-1])]
        L += ['## %s (%s)' % (tag, path), '', '| j | delta lower (down) | delta upper (up) |', '|---|---|---|']
        for w, n in rows:
            if n is None:
                L.append('| %s | (no node at this j) | |' % w)
                continue
            jl = n['j_dec'] if w == 'last' else str(w)
            L.append('| %s | %s | %s |' % (jl, down(F(n['delta_lo'])), up(F(n['delta_hi']))))
        L.append('')
    c = load('p2c/ceiling_p2c.json')
    L += ['## P2c ceiling (p2c/ceiling_p2c.json)', '',
          '- c (rounded up, 20 decimals): %s; c < 1: %s' % (up(F(c['c']), 20), c['c_lt_1']), '']
    for tag, path in (('P2d', 'p2d/result_p2d.json'), ('P2e', 'p2e/result_p2e.json')):
        d = load(path)
        L += ['## %s (%s)' % (tag, path), '',
              '- supremum window [X3 rounded down, c rounded up] (20 decimals): [%s, %s]' % (down(F(d['X3']), 20), up(F(d['c']), 20)),
              '- c - X3 (rounded up, 12 decimals): %s' % up(F(d['c']) - F(d['X3']), 12), '',
              '| k (j = 2^k) | delta lower (down) | delta upper (up) |', '|---|---|---|']
        for n in d['nodes']:
            p = n['point']
            L.append('| %d | %s | %s |' % (n['k'], down(F(p['delta_lo_exact'])), up(F(p['delta_hi_exact']))))
        L.append('')
    b = load('b3t/result_b3t.json')['window']
    L += ['## B3T (b3t/result_b3t.json), extreme data mu = 0, J = 1', '',
          '- chi(0) window (20 decimals): [%s, %s]' % (down(F(b['chi_lo']), 20), up(F(b['chi_hi']), 20)),
          '- M_0 window (16 decimals): [%s, %s]' % (down(F(b['M_lo']), 16), up(F(b['M_up']), 16)), '']
    with open(os.path.join(R, 'DISPLAY-TABLES.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L) + '\n')
    print('wrote results/DISPLAY-TABLES.md')


if __name__ == '__main__':
    main()
